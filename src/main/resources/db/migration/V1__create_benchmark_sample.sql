CREATE TABLE benchmark_sample (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id VARCHAR(100) NOT NULL,
    puuid VARCHAR(100) NOT NULL,
    region VARCHAR(20) NOT NULL,
    queue_id INTEGER NOT NULL,
    tier VARCHAR(20) NOT NULL,
    division VARCHAR(10) NOT NULL,
    rank_captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    champion_id INTEGER NOT NULL,
    position VARCHAR(20) NOT NULL,
    game_version VARCHAR(30) NOT NULL,
    game_start_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    kills INTEGER NOT NULL,
    deaths INTEGER NOT NULL,
    assists INTEGER NOT NULL,
    kda DOUBLE PRECISION NOT NULL,
    cs_per_minute DOUBLE PRECISION NOT NULL,
    gold_per_minute DOUBLE PRECISION NOT NULL,
    damage_per_minute DOUBLE PRECISION NOT NULL,
    vision_per_minute DOUBLE PRECISION NOT NULL,
    kill_participation DOUBLE PRECISION NOT NULL,
    damage_share DOUBLE PRECISION NOT NULL,
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_benchmark_sample_match_puuid UNIQUE (match_id, puuid)
);
