CREATE TABLE benchmark_replenishment_cursor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region VARCHAR(20) NOT NULL,
    queue_id INTEGER NOT NULL,
    tier VARCHAR(20) NOT NULL,
    division VARCHAR(10) NOT NULL,
    next_page INTEGER NOT NULL,
    last_attempted_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_benchmark_replenishment_cursor_cohort UNIQUE (region, queue_id, tier, division),
    CONSTRAINT ck_benchmark_replenishment_cursor_next_page_positive CHECK (next_page > 0)
);
